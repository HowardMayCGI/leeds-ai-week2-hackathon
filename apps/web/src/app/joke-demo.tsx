"use client";

import { useRef, useState } from "react";
import { isJokeResponse } from "@hackathon/api-contract";

type State =
  | { status: "idle" | "loading" }
  | { status: "ready"; joke: string }
  | { status: "error" };

export function JokeDemo() {
  const [state, setState] = useState<State>({ status: "idle" });
  const pending = useRef(false);

  async function tellJoke() {
    if (pending.current) return;
    pending.current = true;
    setState({ status: "loading" });
    try {
      const response = await fetch("/api/joke", {
        method: "POST",
        cache: "no-store",
        signal: AbortSignal.timeout(25_000),
      });
      if (!response.ok) throw new Error("Joke request failed");
      const value: unknown = await response.json();
      if (!isJokeResponse(value)) throw new Error("Invalid joke response");
      setState({ status: "ready", joke: value.joke });
    } catch {
      setState({ status: "error" });
    } finally {
      pending.current = false;
    }
  }

  return (
    <section className="joke-demo" aria-labelledby="joke-demo-title" lang="en" dir="ltr">
      <h2 className="nhsuk-heading-m" id="joke-demo-title">
        Have a laugh
      </h2>
      <p className="nhsuk-body-s">Try a short, family-friendly joke generated by AI.</p>
      <button
        type="button"
        className="nhsuk-button nhsapp-button"
        onClick={tellJoke}
        disabled={state.status === "loading"}
        aria-controls="joke-demo-result"
      >
        {state.status === "loading"
          ? "Getting a joke…"
          : state.status === "error"
            ? "Try again"
            : "Tell me a joke"}
      </button>
      <div id="joke-demo-result" role="status" aria-live="polite" aria-atomic="true">
        {state.status === "loading" && <p className="nhsuk-body-s">Thinking of a joke…</p>}
        {state.status === "ready" && <p className="nhsuk-body joke-demo__joke">{state.joke}</p>}
        {state.status === "error" && (
          <p className="nhsuk-body-s">We could not get a joke right now. Please try again.</p>
        )}
      </div>
    </section>
  );
}
